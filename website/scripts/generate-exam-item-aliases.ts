// Preserve IDs previously assigned to lesson entries that refer to exam questions.
import fs from 'node:fs';
import ENGR213 from '../src/data/gates/engr213';
import INDU211 from '../src/data/gates/indu211';
import MIAE215 from '../src/data/gates/miae215';
import MIAE221 from '../src/data/gates/miae221';

const aliases: Record<string, string> = {};
for (const [course, gate] of Object.entries({ ENGR213, INDU211, MIAE215, MIAE221 })) {
  const examIds = new Set(gate.questions.map((q) => q.id));
  for (const formula of gate.formulas) {
    formula.learn?.quiz.forEach((item, i) => {
      if (item.type !== 'exam') return;
      if (!examIds.has(item.id)) throw new Error(`${course}/${formula.id}: unknown exam question ${item.id}`);
      aliases[`l:${course}:${formula.id}:${i}`] = `x:${course}:${item.id}`;
    });
  }
}
const out = '// Generated by scripts/generate-exam-item-aliases.ts; preserve these progress mappings.\n' +
  'export const EXAM_ITEM_ALIASES: Record<string, string> = ' + JSON.stringify(aliases, null, 2) + ';\n';
fs.writeFileSync('src/learn/progress/examItemAliases.ts', out);
console.log(`Generated ${Object.keys(aliases).length} exam-item aliases.`);
